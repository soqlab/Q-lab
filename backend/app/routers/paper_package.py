# ─── Endpoints ────────────────────────────────────────────────────────────────

@router.get("/{run_id}/paper-package")
def paper_package(run_id: str, db: Session = Depends(get_db)):
    """Return a ZIP containing a complete LaTeX paper skeleton for this run."""
    run = db.scalar(select(Run).where(Run.run_id == run_id))
    if not run:
        raise HTTPException(404, "Run not found")

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("methods.tex", _build_methods(run))
        zf.writestr("results.tex", _build_results(run))
        zf.writestr("calibration.tex", _build_calibration(run))
        zf.writestr("bibliography.bib", _build_bibliography(run))
        zf.writestr("main.tex", _build_main(run))
        if run.qasm:
            zf.writestr("circuit.qasm", run.qasm)

    buf.seek(0)
    filename = f"qlab-{run_id}-paper.zip"
    return Response(
        content=buf.getvalue(),
        media_type="application/zip",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )


@router.get("/{run_id}/overleaf-link")
def overleaf_link(run_id: str, request: Request, db: Session = Depends(get_db)):
    """Return an Overleaf deep-link URL that opens the paper-package ZIP directly."""
    run = db.scalar(select(Run).where(Run.run_id == run_id))
    if not run:
        raise HTTPException(404, "Run not found")

    # Build the absolute URL to the paper-package endpoint so Overleaf can
    # fetch it.  We derive the base URL from the incoming request so this
    # works regardless of deployment host.
    base_url = str(request.base_url).rstrip("/")
    zip_url = f"{base_url}/api/v1/runs/{run_id}/paper-package"
    encoded = urllib.parse.quote(zip_url, safe="")
    overleaf_url = f"https://www.overleaf.com/docs?snip_uri={encoded}"

    return {
        "run_id": run_id,
        "zip_url": zip_url,
        "overleaf_url": overleaf_url,
    }
