# ─── LaTeX helpers ────────────────────────────────────────────────────────────

def _esc(s: str) -> str:
    """Escape special LaTeX characters."""
    replacements = [
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
        ("_", r"\_"), ("{", r"\{"), ("}", r"\}"),
        ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"),
    ]
    for old, new in replacements:
        s = s.replace(old, new)
    return s


def _fmt(v: object, decimals: int = 4) -> str:
    if v is None:
        return "N/A"
    try:
        return f"{float(v):.{decimals}f}"  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return str(v)


# ─── methods.tex ──────────────────────────────────────────────────────────────

def _build_methods(run: Run) -> str:
    fp = run.fingerprint or {}
    ts_raw = run.transpiler or {}
    ts = ts_raw.get("settings") or ts_raw
    ex = run.execution or {}
    params = run.parameters or {}
    backend = run.backend or "unknown"
    shots = params.get("shots") or (run.results or {}).get("shots") or "N/A"

    circuit_rows = "\n".join([
        f"    Circuit name & \\texttt{{{_esc(run.circuit_name or run.run_id)}}} \\\\",
        f"    Qubits & {fp.get('num_qubits', 'N/A')} \\\\",
        f"    Classical bits & {fp.get('num_clbits', 'N/A')} \\\\",
        f"    Circuit depth & {fp.get('depth', 'N/A')} \\\\",
        f"    Gate count & {fp.get('size', 'N/A')} \\\\",
        f"    Non-Clifford ratio & {_fmt(fp.get('non_clifford_ratio'), 3)} \\\\",
    ])

    hw_rows = "\n".join([
        f"    Backend & {_esc(backend)} \\\\",
        f"    Shots & {_esc(str(shots))} \\\\",
        f"    Job class & {_esc(str(ex.get('job_class', 'N/A')))} \\\\",
        f"    Job ID & \\texttt{{{_esc(str(ex.get('job_id', 'N/A')))}}} \\\\",
    ])

    transpiler_rows = "\n".join([
        f"    Optimization level & {ts.get('optimization_level', 'N/A')} \\\\",
        f"    Routing method & {_esc(str(ts.get('routing_method', 'N/A')))} \\\\",
        f"    Layout method & {_esc(str(ts.get('layout_method', 'N/A')))} \\\\",
        f"    Transpile time (ms) & {_fmt(ts_raw.get('duration_ms'), 1)} \\\\",
        f"    Seed (transpiler) & {ts.get('seed_transpiler', 'N/A')} \\\\",
    ])

    return textwrap.dedent(f"""\
% methods.tex — auto-generated by Q-Lab
% Run {run.run_id}

\\subsection{{Circuit Description}}

\\begin{{table}}[htbp]
  \\centering
  \\caption{{Circuit properties for run \\texttt{{{_esc(run.run_id)}}}}}
  \\label{{tab:circuit-{_esc(run.run_id)[:16]}}}
  \\begin{{tabular}}{{ll}}
    \\toprule
    \\textbf{{Property}} & \\textbf{{Value}} \\\\
    \\midrule
{circuit_rows}
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}

\\subsection{{Hardware and Execution Parameters}}

\\begin{{table}}[htbp]
  \\centering
  \\caption{{Hardware specification and execution parameters}}
  \\label{{tab:hardware-{_esc(run.run_id)[:16]}}}
  \\begin{{tabular}}{{ll}}
    \\toprule
    \\textbf{{Parameter}} & \\textbf{{Value}} \\\\
    \\midrule
{hw_rows}
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}

\\subsection{{Transpiler Configuration}}

\\begin{{table}}[htbp]
  \\centering
  \\caption{{Transpiler settings}}
  \\label{{tab:transpiler-{_esc(run.run_id)[:16]}}}
  \\begin{{tabular}}{{ll}}
    \\toprule
    \\textbf{{Setting}} & \\textbf{{Value}} \\\\
    \\midrule
{transpiler_rows}
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
""")


# ─── results.tex ──────────────────────────────────────────────────────────────

def _build_results(run: Run) -> str:
    res = run.results or {}
    fp = run.fingerprint or {}
    run_dict = {
        "results": res,
        "calibration": run.calibration or {},
        "fingerprint": fp,
    }
    health = compute_health_score(run_dict)

    # Build pgfplots histogram from counts if available
    counts: dict = res.get("counts") or res.get("measurement_counts") or {}
    histogram_code = ""
    if counts and isinstance(counts, dict):
        # Take top 16 states by count for readability
        sorted_counts = sorted(counts.items(), key=lambda x: -x[1])[:16]
        total = sum(c for _, c in sorted_counts)
        coords = "\n        ".join(
            f"({_esc(state)},{count/total:.4f})"
            for state, count in sorted_counts
        )
        histogram_code = textwrap.dedent(f"""\
\\subsection{{Measurement Histogram}}

\\begin{{figure}}[htbp]
  \\centering
  \\begin{{tikzpicture}}
    \\begin{{axis}}[
      ybar,
      bar width=6pt,
      xlabel={{Bitstring}},
      ylabel={{Relative frequency}},
      title={{Measurement outcomes for run \\texttt{{{_esc(run.run_id)}}}}},
      xtick=data,
      xticklabel style={{rotate=45,anchor=east,font=\\tiny}},
      ymin=0,
      width=0.9\\textwidth,
      height=6cm,
    ]
      \\addplot coordinates {{
        {coords}
      }};
    \\end{{axis}}
  \\end{{tikzpicture}}
  \\caption{{Normalised measurement histogram (top {len(sorted_counts)} bitstrings shown).}}
  \\label{{fig:histogram-{_esc(run.run_id)[:16]}}}
\\end{{figure}}

""")

    metrics_rows_list = []
    if res.get("success_probability") is not None:
        metrics_rows_list.append(
            f"    Success probability & {_fmt(res['success_probability'], 4)} \\\\"
        )
    if health is not None:
        metrics_rows_list.append(
            f"    Health score (0--100) & {_fmt(health, 1)} \\\\"
        )
    if run.shadow_results:
        sr = run.shadow_results or {}
        if sr.get("tvd") is not None:
            metrics_rows_list.append(
                f"    TVD (shadow simulation) & {_fmt(sr['tvd'], 4)} \\\\"
            )
    metrics_rows = "\n".join(metrics_rows_list) or "    \\multicolumn{2}{c}{No metrics available} \\\\"

    return textwrap.dedent(f"""\
% results.tex — auto-generated by Q-Lab
% Run {run.run_id}

{histogram_code}\\subsection{{Key Metrics}}

\\begin{{table}}[htbp]
  \\centering
  \\caption{{Key results for run \\texttt{{{_esc(run.run_id)}}}}}
  \\label{{tab:results-{_esc(run.run_id)[:16]}}}
  \\begin{{tabular}}{{ll}}
    \\toprule
    \\textbf{{Metric}} & \\textbf{{Value}} \\\\
    \\midrule
{metrics_rows}
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}

\\subsection{{Health Score Breakdown}}

The Q-Lab health score aggregates gate error, decoherence, and readout
fidelity into a single 0--100 composite metric~\\cite{{qlab}}.
This run achieved a score of \\textbf{{{_fmt(health, 1)}}}/100.
""")


# ─── calibration.tex ──────────────────────────────────────────────────────────

def _build_calibration(run: Run) -> str:
    cal = run.calibration or {}
    backend = run.backend or "unknown"
    submitted = run.created_at.isoformat()[:19] if run.created_at else "N/A"

    rows_list = []
    for key, val in list(cal.items())[:30]:
        if not isinstance(val, dict):
            continue
        ge = _fmt(val.get("gate_error") or val.get("cx_error"), 5)
        t1 = _fmt(val.get("T1") or val.get("t1"), 1)
        t2 = _fmt(val.get("T2") or val.get("t2"), 1)
        ro = _fmt(val.get("readout_error"), 4)
        rows_list.append(
            f"    {_esc(str(key))} & {ge} & {t1} & {t2} & {ro} \\\\"
        )

    cal_rows = "\n".join(rows_list) or (
        "    \\multicolumn{5}{c}{No per-qubit calibration data captured} \\\\"
    )

    # Summary row if aggregate data present
    summary = ""
    agg_keys = ["avg_gate_error", "avg_readout_error", "avg_t1_us", "avg_t2_us"]
    if any(cal.get(k) is not None for k in agg_keys):
        summary = textwrap.dedent(f"""\

\\subsection*{{Aggregate Calibration Summary}}

\\begin{{table}}[htbp]
  \\centering
  \\caption{{Backend aggregate metrics at time of submission}}
  \\begin{{tabular}}{{ll}}
    \\toprule
    \\textbf{{Metric}} & \\textbf{{Value}} \\\\
    \\midrule
    Average gate error & {_fmt(cal.get('avg_gate_error'), 5)} \\\\
    Average readout error & {_fmt(cal.get('avg_readout_error'), 5)} \\\\
    Average T1 (\\textmu s) & {_fmt(cal.get('avg_t1_us'), 1)} \\\\
    Average T2 (\\textmu s) & {_fmt(cal.get('avg_t2_us'), 1)} \\\\
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
""")

    return textwrap.dedent(f"""\
% calibration.tex — auto-generated by Q-Lab
% Run {run.run_id}  ·  Backend: {backend}  ·  Snapshot: {submitted} UTC

\\section{{Hardware Calibration Appendix}}

Calibration data was captured automatically at submission time
({_esc(submitted)} UTC) for backend \\textit{{{_esc(backend)}}}.

\\begin{{table}}[htbp]
  \\centering
  \\caption{{Per-qubit/gate calibration snapshot for {_esc(backend)}}}
  \\label{{tab:calibration-{_esc(run.run_id)[:16]}}}
  \\begin{{tabular}}{{lrrrr}}
    \\toprule
    \\textbf{{Qubit/Gate}} & \\textbf{{Gate err.}} & \\textbf{{T1 (\\textmu s)}} & \\textbf{{T2 (\\textmu s)}} & \\textbf{{Readout err.}} \\\\
    \\midrule
{cal_rows}
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
{summary}""")


