      {links.map(({ href, icon: Icon, label }) => (
        <Link
          key={href}
          className={`nav-link${pathname === href ? " active" : ""}`}
          href={href}
        >
          <Icon size={18} aria-hidden="true" />
          {label}
        </Link>
      ))}
